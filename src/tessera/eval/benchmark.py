"""The Faithfulness Floor benchmark — ungated retrieval vs the gated engine.

The launch-facing credibility artifact (spec 0122): what does an agent
*without* an evidence gate do on the same corpus, same questions, judged by
the same verifier? Deterministic, offline, no LLM anywhere in the
measurement; reproducible from a clone with ``uv run tessera-benchmark``.
The written report is
``docs/BENCHMARK.md``; a test pins its tables to this module's fresh output,
so the published numbers cannot silently drift from the measured truth.

Design (the honesty guards, recorded in spec 0122):

- **The baseline is Tessera's own retrieval layer, ungated** —
  :func:`tessera.retrieval.answer` (BM25 top-5 verbatim snippets, refusing
  only on zero content-token overlap), i.e. the system minus routing,
  composition, recomputation, answer-time entity resolution, principled
  refusal, and verification. The measured gap is attributable to exactly the
  layers above retrieval; the baseline is not an authored strawman.
- **Everything else is shared:** the registered batteries' corpora, gold and
  synthetic cases, claim shapes, and the harness's own scoring function
  (``_score`` is deliberately imported, not reimplemented, so benchmark
  semantics cannot drift from eval semantics). Both sides are scored with
  ``index=None`` — the deterministic lexical path — regardless of any
  embeddings environment, so anyone reproduces the same bytes.
- **Recitation's trivial faithfulness is a finding, not a flaw to hide:** the
  ungated side's claims are verbatim snippets and pass containment by
  construction. The report says so prominently — a system that only recites
  is trivially "faithful" and still answers questions it should refuse and
  cannot state what the evidence adds up to.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, replace
from typing import TYPE_CHECKING

from tessera.eval.battery import Battery, GoldCase
from tessera.eval.harness import _score, load_gold_set
from tessera.grounding import Answer, KnowledgeBase
from tessera.retrieval import answer as retrieve_and_recite

if TYPE_CHECKING:
    from tessera.graph import KnowledgeGraph, Node
    from tessera.semantic import SemanticRetriever

# The baseline's retrieval depth — retrieval.answer's own default, stated
# explicitly because the report quotes it.
UNGATED_K = 5

# docs/BENCHMARK.md embeds the generated tables between these markers; the
# pinning test regenerates and compares byte-for-byte.
DOC_BEGIN = (
    "<!-- benchmark:begin (generated by "
    "`uv run tessera-benchmark --markdown`; do not edit by hand) -->"
)
DOC_END = "<!-- benchmark:end -->"

UNGATED_NAME = "ungated retrieval"
TESSERA_NAME = "Tessera (gated)"


def ungated_answer(
    case: GoldCase,
    graph: KnowledgeGraph,
    kb: KnowledgeBase,
    index: SemanticRetriever | None = None,
) -> Answer:
    """The retrieve-and-recite baseline, as a battery answerer.

    Ignores the case's engine dispatch, the graph, and any semantic index *by
    design* — an ungated agent has no routing, no composition, no entity
    layer, no gate. It answers with the top-``UNGATED_K`` BM25 snippets and
    refuses only when the question shares no content token with any record.
    """
    return retrieve_and_recite(case.question, kb, k=UNGATED_K)


def ungated_variant(battery: Battery) -> Battery:
    """``battery`` with ONLY the answerer swapped (spec 0122 decisions 1–2).

    Corpus builders, gold directory, synthetic generator, and claim shapes are
    the original battery's own — the baseline is scored with every grammar the
    real system gets (shared by design; for verbatim claims the vertical
    shapes return no verdict and generic containment decides, so they are
    moot rather than an advantage).
    """
    return replace(battery, answer=ungated_answer)


@dataclass(frozen=True)
class CaseOutcome:
    """One case, one answerer: which of the eval's checks passed.

    Each flag is a single-case run of the harness's ``_score`` (exact eval
    semantics, including its vacuous-1.0 conventions — e.g. refuse-kind cases
    carry no coverage expectation).
    """

    case_id: str
    kind: str
    engine: str
    faithful: bool  # every emitted claim passes the verifier
    covered: bool  # all expected supporting evidence is cited
    correct: bool  # right disposition (answer/refuse) + expected facts present

    @property
    def trustworthy(self) -> bool:
        """The composite: nothing unsupported, nothing missing, nothing wrong."""
        return self.faithful and self.covered and self.correct

    def marks(self) -> str:
        """Compact cell for the per-case tables: ``✓`` or the failed checks."""
        if self.trustworthy:
            return "✓"
        failed = [
            label
            for label, passed in (
                ("F", self.faithful),
                ("C", self.covered),
                ("Q", self.correct),
            )
            if not passed
        ]
        return "✗ " + "+".join(failed)


@dataclass(frozen=True)
class SideScores:
    """One answerer's scores over one case set."""

    faithfulness: float
    coverage: float
    quality: float
    trustworthy: float
    cases: tuple[CaseOutcome, ...]


@dataclass(frozen=True)
class StructuralNotes:
    """Computed properties of the cases + corpus, independent of answerer.

    These make the benchmark's definitional boundary a printed fact rather
    than something a reader must reverse-engineer (spec 0122 review finding):
    expected facts on compose/RCA cases are phrased by the gated engine's
    render templates, so an answerer that does not compose (or does not use
    that phrasing) cannot satisfy them regardless of retrieval quality —
    ``facts_reachable`` counts the answer-kind cases where recitation could
    in principle pass the quality check.
    """

    answer_count: int
    refuse_count: int
    # Answer-kind cases with ≥1 expected fact where EVERY fact appears (raw
    # substring, exactly as the harness matches) in at least one record's
    # text — i.e. quality is in-principle winnable by verbatim recitation.
    facts_with_expectations: int
    facts_reachable: int
    # Cases expecting more support ids than the baseline's retrieval depth —
    # full coverage is structurally out of reach for any k=UNGATED_K answerer.
    support_over_k: int
    # Vacuous conventions (harness semantics): answer-kind cases declaring no
    # expected support / no expected facts — those components auto-pass.
    no_expected_support: int
    no_expected_facts: int


def _structural_notes(cases: list[GoldCase], kb: KnowledgeBase) -> StructuralNotes:
    answer_cases = [case for case in cases if case.kind != "refuse"]
    with_facts = [case for case in answer_cases if case.expected_facts]
    # A fact is recitation-reachable iff it occurs verbatim in some record's
    # text (the render joins records with newline-prefixed provenance lines,
    # so a fact cannot span records; matching is raw substring, exactly like
    # the harness's quality check).
    reachable = sum(
        1
        for case in with_facts
        if all(
            any(fact in record.text for record in kb.records)
            for fact in case.expected_facts
        )
    )
    return StructuralNotes(
        answer_count=len(answer_cases),
        refuse_count=len(cases) - len(answer_cases),
        facts_with_expectations=len(with_facts),
        facts_reachable=reachable,
        support_over_k=sum(
            1 for case in cases if len(case.expected_support) > UNGATED_K
        ),
        no_expected_support=sum(
            1 for case in answer_cases if not case.expected_support
        ),
        no_expected_facts=len(answer_cases) - len(with_facts),
    )


@dataclass(frozen=True)
class BenchmarkRow:
    """One battery × one case set, both answerers side by side."""

    battery: str
    case_set: str  # "gold" | "synthetic"
    case_count: int
    tessera: SideScores
    ungated: SideScores
    notes: StructuralNotes


@dataclass(frozen=True)
class BenchmarkReport:
    rows: tuple[BenchmarkRow, ...]

    @property
    def gap_holds_everywhere(self) -> bool:
        """The headline claim: the gated engine's trustworthy-outcome rate is
        strictly above the ungated baseline's on every battery and case set."""
        return all(
            row.tessera.trustworthy > row.ungated.trustworthy for row in self.rows
        )


def _score_side(
    cases: list[GoldCase],
    battery: Battery,
    graph: KnowledgeGraph,
    kb: KnowledgeBase,
    nodes: dict[str, Node],
) -> SideScores:
    """Score one answerer with the harness's own function, twice over.

    The aggregate triple is ONE ``_score`` call over the full list — the
    eval's exact claim-/support-weighted numbers. Per-case outcomes are
    single-case ``_score`` calls, so the trustworthy composite is derived
    from the same semantics rather than a reimplementation. ``index=None``
    always: the benchmark is pinned to the deterministic lexical path.
    """
    faithfulness, coverage, quality = _score(cases, battery, graph, kb, nodes, None)
    outcomes = tuple(
        CaseOutcome(
            case_id=case.id,
            kind=case.kind,
            engine=case.engine,
            faithful=case_scores[0] == 1.0,
            covered=case_scores[1] == 1.0,
            correct=case_scores[2] == 1.0,
        )
        for case in cases
        for case_scores in (_score([case], battery, graph, kb, nodes, None),)
    )
    trustworthy = (
        sum(1 for outcome in outcomes if outcome.trustworthy) / len(outcomes)
        if outcomes
        else 1.0
    )
    return SideScores(
        faithfulness=faithfulness,
        coverage=coverage,
        quality=quality,
        trustworthy=trustworthy,
        cases=outcomes,
    )


def run_benchmark(batteries: tuple[Battery, ...] | None = None) -> BenchmarkReport:
    """Run both answerers over every battery's gold + synthetic cases."""
    if batteries is None:
        from tessera.eval.registry import batteries as registered

        batteries = registered()

    rows: list[BenchmarkRow] = []
    for battery in batteries:
        ungated = ungated_variant(battery)
        graph = battery.build_graph()
        kb = battery.build_kb()
        nodes: dict[str, Node] = {node.id: node for node in graph.nodes}
        gold = load_gold_set(battery.gold_dir)
        synthetic = battery.synthetic(graph, kb)
        for case_set, cases in (("gold", gold), ("synthetic", synthetic)):
            rows.append(
                BenchmarkRow(
                    battery=battery.name,
                    case_set=case_set,
                    case_count=len(cases),
                    tessera=_score_side(cases, battery, graph, kb, nodes),
                    ungated=_score_side(cases, ungated, graph, kb, nodes),
                    notes=_structural_notes(cases, kb),
                )
            )
    return BenchmarkReport(rows=tuple(rows))


def _fmt(value: float) -> str:
    return f"{value:.3f}"


def render_markdown(report: BenchmarkReport) -> str:
    """The canonical generated block embedded in ``docs/BENCHMARK.md``."""
    total = sum(row.case_count for row in report.rows)
    lines = [
        DOC_BEGIN,
        "",
        f"*Mode: offline, deterministic (lexical BM25, no semantic index, no "
        f"LLM); baseline depth k={UNGATED_K}; {total} cases across "
        f"{len({row.battery for row in report.rows})} batteries.*",
        "",
        "| Battery · cases | Answerer | Faithfulness | Coverage | Quality "
        "| Trustworthy outcomes |",
        "|---|---|---|---|---|---|",
    ]
    for row in report.rows:
        label = f"{row.battery} · {row.case_set} ({row.case_count})"
        for name, side in ((TESSERA_NAME, row.tessera), (UNGATED_NAME, row.ungated)):
            lines.append(
                f"| {label} | {name} | {_fmt(side.faithfulness)} | "
                f"{_fmt(side.coverage)} | {_fmt(side.quality)} | "
                f"**{_fmt(side.trustworthy)}** |"
            )
    lines += [
        "",
        "**Trustworthy-outcome gap (gated − ungated):**",
        "",
    ]
    for row in report.rows:
        gap = row.tessera.trustworthy - row.ungated.trustworthy
        lines.append(
            f"- {row.battery} · {row.case_set}: {_fmt(row.tessera.trustworthy)} "
            f"vs {_fmt(row.ungated.trustworthy)} ({'+' if gap >= 0 else ''}{_fmt(gap)})"
        )
    lines += [
        "",
        "**Structural notes (computed — properties of the cases and corpus, "
        "independent of answerer).** *reachable Q*: answer-kind cases whose "
        "expected facts all occur verbatim in some record, i.e. where "
        "recitation could in principle pass the quality check — on the rest, "
        "the expected phrasing is the gated engine's own composed output, so "
        "the quality gap there measures whether composition happened at all, "
        "not retrieval quality. *>k support*: cases expecting more evidence "
        "ids than the baseline's retrieval depth (k=5) — full coverage is "
        "structurally out of reach there. *vacuous*: answer-kind cases "
        "declaring no expected support / no expected facts (those components "
        "auto-pass, per the harness's own convention).",
        "",
    ]
    for row in report.rows:
        notes = row.notes
        lines.append(
            f"- {row.battery} · {row.case_set}: {notes.answer_count} answer / "
            f"{notes.refuse_count} refuse · reachable Q "
            f"{notes.facts_reachable}/{notes.facts_with_expectations} · "
            f">k support {notes.support_over_k} · vacuous "
            f"{notes.no_expected_support} support, "
            f"{notes.no_expected_facts} facts"
        )
    lines += [
        "",
        "Per-case outcomes on the curated gold sets (`✓` trustworthy; `✗` with "
        "the failed checks — F: a claim failed the verifier, C: expected "
        "evidence not cited, Q: wrong disposition or expected facts missing):",
        "",
        "| Case | Kind | Engine | Tessera (gated) | Ungated retrieval |",
        "|---|---|---|---|---|",
    ]
    for row in report.rows:
        if row.case_set != "gold":
            continue
        for gated, raw in zip(row.tessera.cases, row.ungated.cases, strict=True):
            lines.append(
                f"| {row.battery}/{gated.case_id} | {gated.kind} | "
                f"{gated.engine} | {gated.marks()} | {raw.marks()} |"
            )
    lines += ["", DOC_END]
    return "\n".join(lines)


def render_cases(report: BenchmarkReport) -> str:
    """Every case — gold and synthetic — with both sides' outcome."""
    lines: list[str] = []
    for row in report.rows:
        lines.append(f"== {row.battery} · {row.case_set} ({row.case_count} cases) ==")
        for gated, raw in zip(row.tessera.cases, row.ungated.cases, strict=True):
            lines.append(
                f"  {gated.case_id:<28} {gated.kind:<7} {gated.engine:<10} "
                f"gated {gated.marks():<7} ungated {raw.marks()}"
            )
    return "\n".join(lines)


def render_summary(report: BenchmarkReport) -> str:
    lines = [
        "The Faithfulness Floor — same corpora, same cases, same verifier "
        f"(offline, deterministic, k={UNGATED_K}).",
        "",
    ]
    for row in report.rows:
        lines.append(
            f"[{row.battery} · {row.case_set}, {row.case_count} case(s)] "
            f"trustworthy outcomes: {TESSERA_NAME} "
            f"{_fmt(row.tessera.trustworthy)} vs {UNGATED_NAME} "
            f"{_fmt(row.ungated.trustworthy)} | faithfulness "
            f"{_fmt(row.tessera.faithfulness)} vs {_fmt(row.ungated.faithfulness)} | "
            f"coverage {_fmt(row.tessera.coverage)} vs {_fmt(row.ungated.coverage)} | "
            f"quality {_fmt(row.tessera.quality)} vs {_fmt(row.ungated.quality)}"
        )
    lines += [
        "",
        "Full method, caveats, and how to attack this: docs/BENCHMARK.md.",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="tessera-benchmark")
    parser.add_argument(
        "--markdown",
        action="store_true",
        help="Emit the canonical generated block embedded in docs/BENCHMARK.md.",
    )
    parser.add_argument(
        "--cases",
        action="store_true",
        help="List every case (gold + synthetic) with both sides' outcome.",
    )
    args = parser.parse_args(argv)

    report = run_benchmark()
    if args.markdown:
        print(render_markdown(report))
    elif args.cases:
        print(render_cases(report))
    else:
        print(render_summary(report))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

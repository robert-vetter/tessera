"""The Auditability Floor — the measured, CI-pinned artifact (spec 0137).

The audit analogue of the Faithfulness Floor (spec 0122): a runner that
proves, on every commit, two properties that can fail —

- **Re-derivation equality (floor 100%).** Every gold case of all three
  committed batteries, emitted as a bundle and verified **out-of-process**
  (a genuinely separate interpreter — the strongest form of "a stranger
  re-runs it offline"), must verify PASS (exit 0).
- **Mutation detection (floor 100%).** A deterministic tamper battery
  (:mod:`tessera.bundle.mutations`) over a representative answer bundle and a
  representative action bundle: every mutant must produce the correct verdict
  class **and** a report that names the broken claim/link.

``docs/AUDITABILITY.md`` embeds the generated block between the markers below;
the pinning test regenerates and compares byte-for-byte, so the number can
never quietly decay. ``tessera-auditability --markdown`` prints the block.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from dataclasses import dataclass

from tessera.bundle import mutations as mut
from tessera.bundle.emit import build_action_bundle, build_bundle, bundle_bytes
from tessera.bundle.verify import verify_bundle
from tessera.eval.harness import load_gold_set
from tessera.eval.registry import batteries

DOC_BEGIN = (
    "<!-- auditability:begin (generated by "
    "`uv run tessera-auditability --markdown`; do not edit by hand) -->"
)
DOC_END = "<!-- auditability:end -->"

# The representative bundles the mutation battery runs on: a business answer
# bundle (aggregates, superlatives — the answer-layer classes) and a devex
# incident action bundle (the wire-request classes).
_ANSWER_DOMAIN = "business"
_ANSWER_QUESTION = "Compare Müller Logistik and Nordwind Logistik totals."
_ACTION = (
    "incident",
    "devex",
    "Why did run R-1042 fail, and has this happened before?",
)

_VERIFY_ONE = (
    "import sys, json\n"
    "from tessera.bundle.verify import verify_bundle\n"
    # Read raw bytes and decode UTF-8 explicitly — never rely on the platform's
    # stdin encoding (Windows defaults to cp1252, which would mangle 'Müller').
    "data = json.loads(sys.stdin.buffer.read().decode('utf-8'))\n"
    "sys.exit(verify_bundle(data).exit_code)\n"
)


@dataclass(frozen=True)
class EqualityRow:
    battery: str
    cases: int
    passed: int

    @property
    def holds(self) -> bool:
        return self.cases == self.passed


@dataclass(frozen=True)
class MutationRow:
    name: str
    expected_exit: int
    observed_exit: int
    cause_named: bool

    @property
    def detected(self) -> bool:
        return self.observed_exit == self.expected_exit and self.cause_named


@dataclass(frozen=True)
class AuditabilityReport:
    equality: tuple[EqualityRow, ...]
    mutations: tuple[MutationRow, ...]

    @property
    def total_cases(self) -> int:
        return sum(row.cases for row in self.equality)

    @property
    def cases_passed(self) -> int:
        return sum(row.passed for row in self.equality)

    @property
    def equality_holds(self) -> bool:
        return all(row.holds for row in self.equality)

    @property
    def detection_holds(self) -> bool:
        return all(row.detected for row in self.mutations)


def _verify_out_of_process(bundle: dict[str, object]) -> int:
    """Verify a bundle in a fresh interpreter — the strongest "a stranger
    re-runs it offline" check. Returns the exit code."""
    proc = subprocess.run(
        [sys.executable, "-c", _VERIFY_ONE],
        input=bundle_bytes(bundle),
        capture_output=True,
    )
    return proc.returncode


def _named(report: object, substring: str) -> bool:
    from tessera.bundle.verify import VerifyReport

    assert isinstance(report, VerifyReport)
    haystacks: list[str] = []
    haystacks.extend(report.structural_problems)
    haystacks.extend(report.integrity_problems)
    haystacks.extend(report.signature_problems)
    haystacks.extend(c.cause for c in report.claims if c.cause)
    if report.answer_cause:
        haystacks.append(report.answer_cause)
    if report.taxonomy_reason:
        haystacks.append(report.taxonomy_reason)
    return any(substring in h for h in haystacks)


def run_auditability(*, out_of_process: bool = True) -> AuditabilityReport:
    """Compute both floors. ``out_of_process=False`` runs the equality check
    in-process (for the fast test path); the CI matrix uses the default."""
    equality: list[EqualityRow] = []
    for battery in batteries():
        cases = load_gold_set(battery.gold_dir)
        passed = 0
        for case in cases:
            bundle = build_bundle(battery.name, case.question)
            code = (
                _verify_out_of_process(bundle)
                if out_of_process
                else verify_bundle(bundle).exit_code
            )
            if code == 0:
                passed += 1
        equality.append(EqualityRow(battery.name, len(cases), passed))

    answer_bundle = build_bundle(_ANSWER_DOMAIN, _ANSWER_QUESTION)
    action_bundle = build_action_bundle(*_ACTION)
    rows: list[MutationRow] = []
    for gen in mut.ANSWER_MUTATIONS:
        m = gen(answer_bundle)
        report = verify_bundle(m.bundle)
        rows.append(
            MutationRow(
                m.name,
                m.expected_exit,
                report.exit_code,
                _named(report, m.expected_cause),
            )
        )
    for gen in mut.ACTION_MUTATIONS:
        m = gen(action_bundle)
        report = verify_bundle(m.bundle)
        rows.append(
            MutationRow(
                m.name,
                m.expected_exit,
                report.exit_code,
                _named(report, m.expected_cause),
            )
        )
    return AuditabilityReport(tuple(equality), tuple(rows))


# --- rendering --------------------------------------------------------------------


_VERDICT = {0: "PASS", 2: "FAIL", 3: "DEGRADED", 4: "TAMPERED"}


def render_markdown(report: AuditabilityReport) -> str:
    lines = [DOC_BEGIN, ""]
    lines.append("**Re-derivation equality** — every committed gold case, emitted as")
    lines.append("a bundle and verified in a separate interpreter, verifies PASS:")
    lines.append("")
    lines.append("| battery | gold cases | re-derived PASS |")
    lines.append("|---|---|---|")
    for row in report.equality:
        lines.append(f"| {row.battery} | {row.cases} | {row.passed} |")
    lines.append(
        f"| **total** | **{report.total_cases}** | **{report.cases_passed}** |"
    )
    verdict = "holds" if report.equality_holds else "**BROKEN**"
    lines.append("")
    lines.append(f"Floor (100%): {verdict}.")
    lines.append("")
    lines.append("**Mutation detection** — each deliberate tamper produces the correct")
    lines.append("verdict class and a report that names the broken claim or link:")
    lines.append("")
    lines.append("| mutation | expected | observed | cause named |")
    lines.append("|---|---|---|---|")
    for mrow in report.mutations:
        exp = f"{_VERDICT[mrow.expected_exit]} ({mrow.expected_exit})"
        obs = f"{_VERDICT[mrow.observed_exit]} ({mrow.observed_exit})"
        named = "yes" if mrow.cause_named else "**no**"
        lines.append(f"| {mrow.name} | {exp} | {obs} | {named} |")
    detected = sum(1 for mrow in report.mutations if mrow.detected)
    verdict = "holds" if report.detection_holds else "**BROKEN**"
    lines.append("")
    lines.append(
        f"Floor (100%): {detected}/{len(report.mutations)} detected — {verdict}."
    )
    lines.append("")
    lines.append(DOC_END)
    return "\n".join(lines)


def render_summary(report: AuditabilityReport) -> str:
    eq = "holds" if report.equality_holds else "BROKEN"
    det = "holds" if report.detection_holds else "BROKEN"
    detected = sum(1 for row in report.mutations if row.detected)
    return (
        f"Auditability Floor: re-derivation equality "
        f"{report.cases_passed}/{report.total_cases} ({eq}); "
        f"mutation detection {detected}/{len(report.mutations)} ({det})."
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="tessera-auditability")
    parser.add_argument(
        "--markdown",
        action="store_true",
        help="Emit the canonical generated block embedded in docs/AUDITABILITY.md.",
    )
    parser.add_argument(
        "--in-process",
        action="store_true",
        help="Run the equality check in-process (faster; the default is a fresh "
        "interpreter per bundle, the true offline-stranger check).",
    )
    args = parser.parse_args(argv)
    report = run_auditability(out_of_process=not args.in_process)
    if args.markdown:
        print(render_markdown(report))
    else:
        print(render_summary(report))
    # A broken floor fails the command, so the gate goes red.
    return 0 if (report.equality_holds and report.detection_holds) else 1


if __name__ == "__main__":
    raise SystemExit(main())
